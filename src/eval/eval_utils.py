    @staticmethod
    def compute_f1_metrics(results: Dict[int, Dict]) -> Dict:
        """
        Compute F1, precision, recall from detailed evaluation results.
        
        Args:
            results: List of detailed evaluation results
            
        Returns:
            Dictionary with F1 metrics, macro F1, and TP/FP/FN/TN counts
        """
        tp = sum(1 for _, r in results.items() if r.get('classification') == 'TP')
        fp = sum(1 for _, r in results.items() if r.get('classification') == 'FP')
        fn = sum(1 for _, r in results.items() if r.get('classification') == 'FN')
        tn = sum(1 for _, r in results.items() if r.get('classification') == 'TN')
        
        # Compute standard precision, recall, F1 (for positive class)
        precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
        recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
        f1_positive = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0
        
        precision_negative = tn / (tn + fn) if (tn + fn) > 0 else 0.0
        recall_negative = tn / (tn + fp) if (tn + fp) > 0 else 0.0
        f1_negative = 2 * (precision_negative * recall_negative) / (precision_negative + recall_negative) if (precision_negative + recall_negative) > 0 else 0.0
        
        # Macro F1 is the average of F1 scores for both classes
        macro_f1 = (f1_positive + f1_negative) / 2.0

        # Compute accuracy
        accuracy = (tp + tn) / len(results) if len(results) > 0 else 0.0

        return {
            'tp': tp,
            'fp': fp,
            'fn': fn,
            'tn': tn,
            'precision': precision,
            'recall': recall,
            'macro_f1': macro_f1,
            'f1_positive': f1_positive,
            'f1_negative': f1_negative,
            'precision_negative': precision_negative,
            'recall_negative': recall_negative,
            'accuracy': accuracy
        }
    
    @staticmethod
    def aggregate_artifact_type_stats(results: Dict[int, Dict]) -> Dict[str, Dict[str, float]]:
        """
        Aggregate per-artifact-type statistics from evaluation results.
        
        Args:
            results: Dictionary of evaluation results with artifact_type_stats
            
        Returns:
            Dictionary with aggregated statistics per artifact type including 
            total count, matched count, and detection rate
        """
        aggregated = {
            'addition': {'total': 0, 'matched': 0, 'detection_rate': 0.0},
            'removal': {'total': 0, 'matched': 0, 'detection_rate': 0.0},
            'distortion': {'total': 0, 'matched': 0, 'detection_rate': 0.0},
            'fusion': {'total': 0, 'matched': 0, 'detection_rate': 0.0}
        }
        
        for _, result in results.items():
            type_stats = result.get('artifact_type_stats')
            if type_stats is not None and isinstance(type_stats, dict):
                for artifact_type in ['addition', 'removal', 'distortion', 'fusion']:
                    if artifact_type in type_stats:
                        aggregated[artifact_type]['total'] += type_stats[artifact_type].get('total', 0)
                        aggregated[artifact_type]['matched'] += type_stats[artifact_type].get('matched', 0)
        
        # Compute detection rates
        for artifact_type in aggregated:
            total = aggregated[artifact_type]['total']
            matched = aggregated[artifact_type]['matched']
            if total > 0:
                aggregated[artifact_type]['detection_rate'] = matched / total
            else:
                aggregated[artifact_type]['detection_rate'] = 0.0
        
        return aggregated