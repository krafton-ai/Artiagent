def parse_json(response: str):
    """
    Try to extract valid JSON (object or array) from a response string that may include 
    markdown fences, incomplete JSON, or trailing commas.
    Returns the parsed Python object, or raises a ValueError if it can't.
    """
    if not isinstance(response, str):
        raise ValueError(f"Expected string input, got {type(response)}: {response}")
    
    # 1) Strip markdown fences ```json ... ``` or ```python ... ```
    cleaned = re.sub(r"```(?:json|python)?\s*", "", response)
    cleaned = re.sub(r"\s*```", "", cleaned).strip()
    
    # 2) Try to find the JSON content (object or array)
    json_content = None
    obj_match = re.search(r'\{.*\}', cleaned, re.DOTALL)
    arr_match = re.search(r'\[.*\]', cleaned, re.DOTALL)

    # Prefer array if found, otherwise object
    if arr_match:
        json_content = arr_match.group()
    elif obj_match:
        json_content = obj_match.group()
    else:
        json_content = cleaned

    # 3) Clean up common issues (e.g., trailing commas)
    json_content = re.sub(r",\s*([\]}])", r"\1", json_content)
    json_content = json_content.strip()

    # 4) Try to parse JSON directly
    try:
        return json.loads(json_content)
    except json.JSONDecodeError as e:
        # Try fixing common JSON issues and retry
        try:
            fixed = re.sub(r"\b(true|false|null)\b", lambda m: f'"{m.group(1)}"', json_content)
            fixed = re.sub(r'"(true|false|null)"', lambda m: m.group(1), fixed)
            return json.loads(fixed)
        except json.JSONDecodeError:
            pass

        raise ValueError(f"Failed to decode JSON from response. Original error: {e}\nContent: {json_content!r}\nFull response: {response!r}")

class Evaluation:
    """
    Provides utilities for evaluating artifact detection performance.
    
    This class computes various metrics including IoU, ROUGE-L scores,
    and cosine similarity scores for artifact detection evaluation.
    """
    
    def __init__(self):
        """Initialize evaluation metrics."""
        if SentenceTransformer is not None:
            self.css_model = SentenceTransformer('sentence-transformers/paraphrase-MiniLM-L6-v2')
        else:
            self.css_model = None
            
        if rouge_scorer is not None:
            self.rouge_scorer = rouge_scorer.RougeScorer(['rouge1', 'rougeL'], use_stemmer=True)
        else:
            self.rouge_scorer = None

    @staticmethod
    def _compute_iou(boxA: List[float], boxB: List[float]) -> float:
        """
        Compute the Intersection over Union (IoU) of two bounding boxes.
        
        Args:
            boxA: Bounding box in format [x1, y1, x2, y2]
            boxB: Bounding box in format [x1, y1, x2, y2]
            
        Returns:
            IoU score between 0 and 1
        """
        # Determine intersection coordinates
        xA = max(boxA[0], boxB[0])
        yA = max(boxA[1], boxB[1])
        xB = min(boxA[2], boxB[2])
        yB = min(boxA[3], boxB[3])

        # Compute intersection area
        interW = max(0, xB - xA)
        interH = max(0, yB - yA)
        interArea = interW * interH

        if interArea == 0:
            return 0.0

        # Compute union area
        boxAArea = (boxA[2] - boxA[0]) * (boxA[3] - boxA[1])
        boxBArea = (boxB[2] - boxB[0]) * (boxB[3] - boxB[1])
        unionArea = boxAArea + boxBArea - interArea
        
        return interArea / float(unionArea) if unionArea > 0 else 0.0

    @staticmethod
    def _compute_iou_polygon(seg: List[float], bbox: List[float]) -> float:
        """
        Compute the Intersection over Union (IoU) of a polygonal segmentation and a bbox.
        
        Args:
            seg: Polygon coordinates as flat list [x1, y1, x2, y2, ..., xn, yn]
            bbox: Bounding box in format [x1, y1, x2, y2]
            
        Returns:
            IoU score between 0 and 1
        """
        try:
            if Polygon is None or box is None:
                # Shapely not available, fallback to 0
                return 0.0
                
            # Convert flat coordinates to point pairs
            poly_points = [(seg[i], seg[i+1]) for i in range(0, len(seg), 2)]
            
            # Create Shapely polygons
            seg_poly = Polygon(poly_points)
            x1, y1, x2, y2 = bbox
            bbox_poly = box(x1, y1, x2, y2)
            
            # Compute intersection and union
            intersection = seg_poly.intersection(bbox_poly).area
            union = seg_poly.union(bbox_poly).area
            
            return intersection / union if union > 0 else 0.0
            
        except Exception:
            # Fallback to 0 if polygon operations fail
            return 0.0

    @staticmethod
    def _normalize_heatmap(heatmap: np.ndarray) -> np.ndarray:
        """
        Per-image min-max normalization of heatmap as described in the reference paper.
        
        Args:
            heatmap: Input heatmap array
            
        Returns:
            Normalized heatmap with values between 0 and 1
        """
        # Ensure 2D
        if len(heatmap.shape) == 4:
            heatmap = heatmap[0, 0]
        elif len(heatmap.shape) == 3:
            heatmap = heatmap[:, :, 0]
            
        # Min-max normalization
        min_val = np.min(heatmap)
        max_val = np.max(heatmap)
        
        if max_val - min_val > 0:
            normalized = (heatmap - min_val) / (max_val - min_val)
        else:
            normalized = np.zeros_like(heatmap)
            
        return normalized.astype(np.float32)
    
    @staticmethod
    def _heatmap_to_tightest_bbox(heatmap: np.ndarray, threshold: float, image_width: int, image_height: int) -> List[float]:
        """
        Convert heatmap to tightest bounding box using threshold.
        
        Args:
            heatmap: Normalized heatmap
            threshold: Threshold value
            image_width: Width for scaling coordinates
            image_height: Height for scaling coordinates
            
        Returns:
            Bounding box in format [x1, y1, x2, y2], empty list if no regions found
        """
        # Threshold heatmap
        binary_mask = (heatmap > threshold).astype(np.uint8)
        
        # Find coordinates of positive pixels
        coords = np.where(binary_mask > 0)
        if len(coords[0]) == 0:
            return []
            
        # Get bounding box
        y_min, y_max = np.min(coords[0]), np.max(coords[0])
        x_min, x_max = np.min(coords[1]), np.max(coords[1])
        
        # Scale to image coordinates
        h, w = heatmap.shape
        x1 = (x_min / w) * image_width
        y1 = (y_min / h) * image_height
        x2 = (x_max / w) * image_width  
        y2 = (y_max / h) * image_height
        
        return [x1, y1, x2, y2]
    
    @staticmethod
    def _segmentation_to_tightest_bbox(segmentation: List[float], image_width: int, image_height: int) -> List[float]:
        """
        Convert segmentation polygon to tightest bounding box.
        
        Args:
            segmentation: Polygon coordinates as flat list [x1, y1, x2, y2, ..., xn, yn]
            image_width: Image width 
            image_height: Image height
            
        Returns:
            Bounding box in format [x1, y1, x2, y2]
        """
        if len(segmentation) < 6:  # At least 3 points needed
            return []
            
        # Extract x and y coordinates
        x_coords = [segmentation[i] for i in range(0, len(segmentation), 2)]
        y_coords = [segmentation[i] for i in range(1, len(segmentation), 2)]
        
        # Get bounding box
        x1 = max(0, min(x_coords))
        y1 = max(0, min(y_coords))
        x2 = min(image_width, max(x_coords))
        y2 = min(image_height, max(y_coords))
        
        return [x1, y1, x2, y2]
    
    @staticmethod
    def _compute_threshold_independent_bbox_metrics(
        pred_data: Any,
        gt_data: Any,
        pred_type: str,
        gt_type: str,
        image_width: int,
        image_height: int,
        num_thresholds: int = 100,
        return_matching: bool = False
    ) -> Union[Dict[str, float], Tuple[Dict[str, float], Dict[int, int]]]:
        """
        Compute threshold-independent IoU and F1 metrics by converting everything to bboxes.
        
        Args:
            pred_data: Prediction data (heatmap, bbox, or segmentation)
            gt_data: Ground truth data (heatmap, bbox, or segmentation)
            pred_type: Type of prediction ('heatmap', 'bbox', 'segmentation') 
            gt_type: Type of ground truth ('heatmap', 'bbox', 'segmentation')
            image_width: Image width
            image_height: Image height
            num_thresholds: Number of thresholds to sweep
            return_matching: If True, also return matching dict (GT idx -> pred idx)
            
        Returns:
            Dictionary with best IoU and F1 metrics across all thresholds
            If return_matching=True, returns tuple of (metrics_dict, matching_dict)
        """
        thresholds = np.linspace(0.0, 1.0, num_thresholds)
        best_metrics = {
            'iou': 0.0,
            'loc_tp': 0,
            'loc_fp': 0,
            'loc_fn': 0,
            'loc_precision': 0.0,
            'loc_recall': 0.0,
            'loc_f1': 0.0
        }
        best_matching = {}  # Track best matching when return_matching=True
        
        # Convert ground truth to bbox
        gt_bboxes = []
        if gt_type == 'bbox':
            if isinstance(gt_data, list) and len(gt_data) > 0:
                if isinstance(gt_data[0], list):
                    gt_bboxes = gt_data  # Multiple bboxes
                else:
                    gt_bboxes = [gt_data]  # Single bbox
        elif gt_type == 'segmentation':
            if isinstance(gt_data, list) and len(gt_data) > 0:
                if isinstance(gt_data[0], list):
                    # Multiple segmentations
                    for seg in gt_data:
                        bbox = Evaluation._segmentation_to_tightest_bbox(seg, image_width, image_height)
                        if bbox:
                            gt_bboxes.append(bbox)
                else:
                    # Single segmentation
                    bbox = Evaluation._segmentation_to_tightest_bbox(gt_data, image_width, image_height)
                    if bbox:
                        gt_bboxes.append(bbox)
        elif gt_type == 'heatmap':
            # For GT heatmap, use a single threshold to extract bbox
            gt_norm = Evaluation._normalize_heatmap(gt_data)
            gt_bbox = Evaluation._heatmap_to_tightest_bbox(gt_norm, 0.3, image_width, image_height)
            if gt_bbox:
                gt_bboxes = [gt_bbox]
        
        if not gt_bboxes:
            if return_matching:
                return best_metrics, best_matching
            return best_metrics
        
        # Convert predictions to bboxes and sweep thresholds
        if pred_type == 'bbox':
            pred_bboxes = []
            if isinstance(pred_data, list) and len(pred_data) > 0:
                if isinstance(pred_data[0], list):
                    pred_bboxes = pred_data  # Multiple bboxes
                else:
                    pred_bboxes = [pred_data]  # Single bbox
            
            # For bbox predictions, no threshold sweep needed
            if pred_bboxes:
                # Compute IoU
                iou, matching = Evaluation._match_and_mean_iou(gt_bboxes, pred_bboxes, use_polygons=False)
                # Compute F1
                f1_metrics = Evaluation._compute_localization_f1(gt_bboxes, pred_bboxes, use_polygons=False, iou_threshold=0.5)
                
                if iou > best_metrics['iou']:
                    best_metrics.update({
                        'iou': iou,
                        'loc_tp': f1_metrics['tp'],
                        'loc_fp': f1_metrics['fp'],
                        'loc_fn': f1_metrics['fn'],
                        'loc_precision': f1_metrics['precision'],
                        'loc_recall': f1_metrics['recall'],
                        'loc_f1': f1_metrics['f1']
                    })
                    best_matching = matching
                    
        elif pred_type == 'segmentation':
            pred_bboxes = []
            if isinstance(pred_data, list) and len(pred_data) > 0:
                if isinstance(pred_data[0], list):
                    # Multiple segmentations
                    for seg in pred_data:
                        bbox = Evaluation._segmentation_to_tightest_bbox(seg, image_width, image_height)
                        if bbox:
                            pred_bboxes.append(bbox)
                else:
                    # Single segmentation
                    bbox = Evaluation._segmentation_to_tightest_bbox(pred_data, image_width, image_height)
                    if bbox:
                        pred_bboxes.append(bbox)
            
            # For segmentation predictions, no threshold sweep needed
            if pred_bboxes:
                # Compute IoU
                iou, matching = Evaluation._match_and_mean_iou(gt_bboxes, pred_bboxes, use_polygons=False)
                # Compute F1
                f1_metrics = Evaluation._compute_localization_f1(gt_bboxes, pred_bboxes, use_polygons=False, iou_threshold=0.5)
                
                if iou > best_metrics['iou']:
                    best_metrics.update({
                        'iou': iou,
                        'loc_tp': f1_metrics['tp'],
                        'loc_fp': f1_metrics['fp'],
                        'loc_fn': f1_metrics['fn'],
                        'loc_precision': f1_metrics['precision'],
                        'loc_recall': f1_metrics['recall'],
                        'loc_f1': f1_metrics['f1']
                    })
                    best_matching = matching
                    
        elif pred_type == 'heatmap':
            # For heatmap predictions, sweep thresholds
            pred_norm = Evaluation._normalize_heatmap(pred_data)
            
            for tau in thresholds:
                pred_bbox = Evaluation._heatmap_to_tightest_bbox(pred_norm, tau, image_width, image_height)
                if not pred_bbox:
                    continue
                    
                pred_bboxes = [pred_bbox]
                
                # Compute IoU
                iou, matching = Evaluation._match_and_mean_iou(gt_bboxes, pred_bboxes, use_polygons=False)
                # Compute F1
                f1_metrics = Evaluation._compute_localization_f1(gt_bboxes, pred_bboxes, use_polygons=False, iou_threshold=0.5)
                
                # Keep the best metrics across all thresholds
                if iou > best_metrics['iou']:
                    best_metrics.update({
                        'iou': iou,
                        'loc_tp': f1_metrics['tp'],
                        'loc_fp': f1_metrics['fp'],
                        'loc_fn': f1_metrics['fn'],
                        'loc_precision': f1_metrics['precision'],
                        'loc_recall': f1_metrics['recall'],
                        'loc_f1': f1_metrics['f1']
                    })
                    best_matching = matching
        
        if return_matching:
            return best_metrics, best_matching
        return best_metrics

    @staticmethod
    def _match_and_mean_iou(
        gt_data: List[Any], 
        est_bboxes: List[List[float]],
        use_polygons: bool = False
    ) -> Tuple[float, Dict[int, int]]:
        """
        Match estimated bboxes to ground truth and compute mean IoU.
        
        For each ground truth annotation, find the best matching estimated bbox
        (highest IoU > 0) and return the mean IoU and mapping.
        
        Args:
            gt_data: Ground truth bboxes or polygon segmentations
            est_bboxes: Estimated bounding boxes
            use_polygons: Whether to use polygon-based IoU computation
            
        Returns:
            Tuple of (mean_iou, mapping_dict)
        """
        if not gt_data or not est_bboxes:
            return 0.0, {}

        mapping = {}  # GT index -> estimated bbox index
        all_ious = []
        
        for gt_idx, gt_item in enumerate(gt_data):
            best_iou = 0.0
            best_est_idx = -1
            
            for est_idx, est_bbox in enumerate(est_bboxes):
                if use_polygons:
                    # gt_item is a polygon segmentation
                    iou = Evaluation._compute_iou_polygon(gt_item, est_bbox)
                else:
                    # gt_item is a bounding box
                    iou = Evaluation._compute_iou(gt_item, est_bbox)
                
                if iou > best_iou:
                    best_iou = iou
                    best_est_idx = est_idx
            
            if best_iou > 0:
                mapping[gt_idx] = best_est_idx
                all_ious.append(best_iou)

        mean_iou = float(np.mean(all_ious)) if all_ious else 0.0
        return mean_iou, mapping

    @staticmethod
    def _compute_localization_f1(
        gt_data: List[Any],
        est_bboxes: List[List[float]],
        use_polygons: bool = False,
        iou_threshold: float = 0.5
    ) -> Dict[str, float]:
        """
        Compute localization F1 score following object detection conventions.
        
        Args:
            gt_data: Ground truth bboxes or polygon segmentations
            est_bboxes: Estimated bounding boxes
            use_polygons: Whether to use polygon-based IoU computation
            iou_threshold: IoU threshold for considering a match (default: 0.5)
            
        Returns:
            Dictionary with TP, FP, FN counts and precision, recall, F1 scores
        """
        if not gt_data and not est_bboxes:
            # Both empty - perfect match
            return {
                'tp': 0, 'fp': 0, 'fn': 0,
                'precision': 1.0, 'recall': 1.0, 'f1': 1.0
            }
        
        if not gt_data:
            # No ground truth but have predictions - all FP
            return {
                'tp': 0, 'fp': len(est_bboxes), 'fn': 0,
                'precision': 0.0, 'recall': 1.0, 'f1': 0.0
            }
            
        if not est_bboxes:
            # Ground truth exists but no predictions - all FN
            return {
                'tp': 0, 'fp': 0, 'fn': len(gt_data),
                'precision': 1.0, 'recall': 0.0, 'f1': 0.0
            }

        # Compute IoU matrix between all GT and predictions
        iou_matrix = np.zeros((len(gt_data), len(est_bboxes)))
        for gt_idx, gt_item in enumerate(gt_data):
            for est_idx, est_bbox in enumerate(est_bboxes):
                if use_polygons:
                    iou = Evaluation._compute_iou_polygon(gt_item, est_bbox)
                else:
                    iou = Evaluation._compute_iou(gt_item, est_bbox)
                iou_matrix[gt_idx, est_idx] = iou

        # Greedy matching: for each GT, find best prediction with IoU > threshold
        matched_predictions = set()
        tp = 0
        
        # Match each ground truth to best available prediction
        for gt_idx in range(len(gt_data)):
            best_iou = 0.0
            best_pred_idx = -1
            
            for pred_idx in range(len(est_bboxes)):
                if pred_idx in matched_predictions:
                    continue  # Already matched
                    
                iou = iou_matrix[gt_idx, pred_idx]
                if iou >= iou_threshold and iou > best_iou:
                    best_iou = iou
                    best_pred_idx = pred_idx
            
            if best_pred_idx != -1:
                matched_predictions.add(best_pred_idx)
                tp += 1
        
        # Count FP: predictions that weren't matched to any GT
        fp = len(est_bboxes) - len(matched_predictions)
        
        # Count FN: ground truths that weren't matched to any prediction
        fn = len(gt_data) - tp
        
        # Compute metrics
        precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
        recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
        f1 = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0
        
        return {
            'tp': tp,
            'fp': fp, 
            'fn': fn,
            'precision': precision,
            'recall': recall,
            'f1': f1
        }

    def _css_score(self, s1: str, s2: str) -> float:
        """
        Compute cosine similarity score between two text strings.
        
        Args:
            s1: First text string
            s2: Second text string
            
        Returns:
            Cosine similarity score
        """
        if self.css_model is None or util is None:
            return 0.0
            
        emb1 = self.css_model.encode(s1, convert_to_tensor=True)
        emb2 = self.css_model.encode(s2, convert_to_tensor=True)
        
        cosine_sim = util.cos_sim(emb1, emb2).cpu().item()
        return cosine_sim

    def compute_global_caption_scores(self, reference: str, hypothesis: str) -> Tuple[float, float]:
        """
        Compute global text scores (ROUGE-L, CSS) between a reference caption and a predicted caption.

        Args:
            reference: Ground-truth caption text
            hypothesis: Predicted caption text

        Returns:
            Tuple of (rouge_l_f1, css_cosine_similarity)
        """
        rouge_l = 0.0
        css = 0.0
        try:
            if self.rouge_scorer is not None and reference and hypothesis:
                score = self.rouge_scorer.score(reference, hypothesis)
                rouge_l = float(score['rougeL'].fmeasure)
        except Exception:
            rouge_l = 0.0
        try:
            if self.css_model is not None and reference and hypothesis:
                css = float(self._css_score(reference, hypothesis))
        except Exception:
            css = 0.0
        return rouge_l, css

    def get_scores(
        self, 
        ground_data: List[Union[List[float], List[List[float]]]], 
        ground_desc_list: List[str], 
        result_bbox_list: List[List[float]], 
        result_desc_list: List[str],
        use_polygons: bool = False
    ) -> Tuple[float, float, float]:
        """
        Compute evaluation scores for artifact detection results.
        
        Args:
            ground_data: Ground truth bboxes or polygon segmentations
            ground_desc_list: Ground truth descriptions
            result_bbox_list: Predicted bounding boxes
            result_desc_list: Predicted descriptions
            use_polygons: Whether to use polygon-based IoU computation
            
        Returns:
            Tuple of (mean_iou, mean_rouge_l, mean_css)
        """
        rouge_scores = []
        css_scores = []

        iou, mapping = self._match_and_mean_iou(
            ground_data, result_bbox_list, use_polygons
        )

        # Compute text-based scores for matched artifacts
        for gt_idx, est_idx in mapping.items():
            if gt_idx < len(ground_desc_list) and est_idx < len(result_desc_list):
                ref = ground_desc_list[gt_idx]
                hyp = result_desc_list[est_idx]
                
                # ROUGE-L score
                if self.rouge_scorer is not None:
                    score = self.rouge_scorer.score(ref, hyp)
                    rouge_scores.append(score['rougeL'].fmeasure)
                else:
                    rouge_scores.append(0.0)
                
                # Cosine similarity score
                css_scores.append(self._css_score(ref, hyp))

        # Compute mean scores, penalizing unmatched ground truth artifacts
        num_gt = len(ground_desc_list)
        mean_rouge_l = np.sum(rouge_scores) / num_gt if num_gt > 0 else 0.0
        mean_css = np.sum(css_scores) / num_gt if num_gt > 0 else 0.0

        return iou, mean_rouge_l, mean_css

