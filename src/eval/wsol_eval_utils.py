    @staticmethod
    def _compute_heatmap_to_heatmap_iou_regionwise(
        pred_heatmap: np.ndarray,
        gt_heatmap: np.ndarray,
        threshold_pred: float = 0.3,
        threshold_gt: float = 0.3,
        min_region_area: int = 10,
    ) -> float:
        """
        Compute mean IoU between connected regions of pred and GT heatmaps via greedy best-match.
        """
        try:
            # Normalize shapes to 2D
            if len(pred_heatmap.shape) == 4:
                pred_heatmap = pred_heatmap[0, 0]
            elif len(pred_heatmap.shape) == 3:
                pred_heatmap = pred_heatmap[:, :, 0]
            if len(gt_heatmap.shape) == 4:
                gt_heatmap = gt_heatmap[0, 0]
            elif len(gt_heatmap.shape) == 3:
                gt_heatmap = gt_heatmap[:, :, 0]

            pred_bin = (pred_heatmap > threshold_pred).astype(np.uint8)
            gt_bin = (gt_heatmap > threshold_gt).astype(np.uint8)

            pred_regions = [r for r in Evaluation._connected_components(pred_bin) if np.sum(r) >= min_region_area]
            gt_regions = [r for r in Evaluation._connected_components(gt_bin) if np.sum(r) >= min_region_area]

            if not pred_regions or not gt_regions:
                return 0.0

            # Compute IoU matrix
            iou_matrix = np.zeros((len(gt_regions), len(pred_regions)), dtype=np.float32)
            for i, g in enumerate(gt_regions):
                for j, p in enumerate(pred_regions):
                    iou_matrix[i, j] = Evaluation._mask_iou(g, p)

            # Greedy matching: for each GT pick best pred and don't reuse preds
            used_pred = set()
            ious = []
            for i in range(len(gt_regions)):
                # pick best available pred
                best_j = -1
                best_iou = 0.0
                for j in range(len(pred_regions)):
                    if j in used_pred:
                        continue
                    val = float(iou_matrix[i, j])
                    if val > best_iou:
                        best_iou = val
                        best_j = j
                if best_j >= 0:
                    used_pred.add(best_j)
                    if best_iou > 0:
                        ious.append(best_iou)

            return float(np.mean(ious)) if ious else 0.0
        except Exception:
            return 0.0

    @staticmethod
    def _match_and_mean_iou(
        gt_data: List[Any], 
        est_bboxes: List[List[float]],
        use_polygons: bool = False
    ) -> Tuple[float, Dict[int, int]]:
        """
        Match estimated bboxes to ground truth and compute mean IoU.
        
        For each ground truth annotation, find the best matching estimated bbox
        (highest IoU > 0) and return the mean IoU and mapping.
        
        Args:
            gt_data: Ground truth bboxes or polygon segmentations
            est_bboxes: Estimated bounding boxes
            use_polygons: Whether to use polygon-based IoU computation
            
        Returns:
            Tuple of (mean_iou, mapping_dict)
        """
        if not gt_data or not est_bboxes:
            return 0.0, {}

        mapping = {}  # GT index -> estimated bbox index
        all_ious = []
        
        for gt_idx, gt_item in enumerate(gt_data):
            best_iou = 0.0
            best_est_idx = -1
            
            for est_idx, est_bbox in enumerate(est_bboxes):
                if use_polygons:
                    # gt_item is a polygon segmentation
                    iou = Evaluation._compute_iou_polygon(gt_item, est_bbox)
                else:
                    # gt_item is a bounding box
                    iou = Evaluation._compute_iou(gt_item, est_bbox)
                
                if iou > best_iou:
                    best_iou = iou
                    best_est_idx = est_idx
            
            if best_iou > 0:
                mapping[gt_idx] = best_est_idx
                all_ious.append(best_iou)

        mean_iou = float(np.mean(all_ious)) if all_ious else 0.0
        return mean_iou, mapping

    @staticmethod
    def _compute_localization_f1(
        gt_data: List[Any],
        est_bboxes: List[List[float]],
        use_polygons: bool = False,
        iou_threshold: float = 0.5
    ) -> Dict[str, float]:
        """
        Compute localization F1 score following object detection conventions.
        
        Args:
            gt_data: Ground truth bboxes or polygon segmentations
            est_bboxes: Estimated bounding boxes
            use_polygons: Whether to use polygon-based IoU computation
            iou_threshold: IoU threshold for considering a match (default: 0.5)
            
        Returns:
            Dictionary with TP, FP, FN counts and precision, recall, F1 scores
        """
        if not gt_data and not est_bboxes:
            # Both empty - perfect match
            return {
                'tp': 0, 'fp': 0, 'fn': 0,
                'precision': 1.0, 'recall': 1.0, 'f1': 1.0
            }
        
        if not gt_data:
            # No ground truth but have predictions - all FP
            return {
                'tp': 0, 'fp': len(est_bboxes), 'fn': 0,
                'precision': 0.0, 'recall': 1.0, 'f1': 0.0
            }
            
        if not est_bboxes:
            # Ground truth exists but no predictions - all FN
            return {
                'tp': 0, 'fp': 0, 'fn': len(gt_data),
                'precision': 1.0, 'recall': 0.0, 'f1': 0.0
            }

        # Compute IoU matrix between all GT and predictions
        iou_matrix = np.zeros((len(gt_data), len(est_bboxes)))
        for gt_idx, gt_item in enumerate(gt_data):
            for est_idx, est_bbox in enumerate(est_bboxes):
                if use_polygons:
                    iou = Evaluation._compute_iou_polygon(gt_item, est_bbox)
                else:
                    iou = Evaluation._compute_iou(gt_item, est_bbox)
                iou_matrix[gt_idx, est_idx] = iou

        # Greedy matching: for each GT, find best prediction with IoU > threshold
        matched_predictions = set()
        tp = 0
        
        # Match each ground truth to best available prediction
        for gt_idx in range(len(gt_data)):
            best_iou = 0.0
            best_pred_idx = -1
            
            for pred_idx in range(len(est_bboxes)):
                if pred_idx in matched_predictions:
                    continue  # Already matched
                    
                iou = iou_matrix[gt_idx, pred_idx]
                if iou >= iou_threshold and iou > best_iou:
                    best_iou = iou
                    best_pred_idx = pred_idx
            
            if best_pred_idx != -1:
                matched_predictions.add(best_pred_idx)
                tp += 1
        
        # Count FP: predictions that weren't matched to any GT
        fp = len(est_bboxes) - len(matched_predictions)
        
        # Count FN: ground truths that weren't matched to any prediction
        fn = len(gt_data) - tp
        
        # Compute metrics
        precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
        recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
        f1 = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0
        
        return {
            'tp': tp,
            'fp': fp, 
            'fn': fn,
            'precision': precision,
            'recall': recall,
            'f1': f1
        }

    @staticmethod
    def _extract_bboxes_from_heatmap(
        heatmap: np.ndarray, 
        threshold: float = 0.3, 
        min_region_area: int = 10,
        image_width: int = 512,
        image_height: int = 512
    ) -> List[List[float]]:
        """
        Extract bounding boxes from heatmap connected components.
        
        Args:
            heatmap: Input heatmap array
            threshold: Threshold for binarizing heatmap
            min_region_area: Minimum area for keeping a region
            image_width: Width to scale bboxes to
            image_height: Height to scale bboxes to
            
        Returns:
            List of bounding boxes in [x1, y1, x2, y2] format
        """
        if heatmap is None:
            return []
            
        try:
            # Normalize heatmap to 2D
            if len(heatmap.shape) == 4:
                heatmap = heatmap[0, 0]
            elif len(heatmap.shape) == 3:
                heatmap = heatmap[:, :, 0]
            
            # Binarize heatmap
            binary_map = (heatmap > threshold).astype(np.uint8)
            
            # Extract connected components
            regions = Evaluation._connected_components(binary_map)
            
            # Filter small regions
            regions = [r for r in regions if np.sum(r) >= min_region_area]
            
            bboxes = []
            h, w = binary_map.shape
            
            for region in regions:
                # Find bounding box of the region
                coords = np.where(region > 0)
                if len(coords[0]) == 0:
                    continue
                    
                y_min, y_max = np.min(coords[0]), np.max(coords[0])
                x_min, x_max = np.min(coords[1]), np.max(coords[1])
                
                # Scale to image coordinates
                x1 = (x_min / w) * image_width
                y1 = (y_min / h) * image_height
                x2 = (x_max / w) * image_width
                y2 = (y_max / h) * image_height
                
                bboxes.append([x1, y1, x2, y2])
            
            return bboxes
            
        except Exception:
            return []

    @staticmethod
    def _compute_heatmap_f1(
        pred_heatmap: np.ndarray,
        gt_data: List[Any],
        use_polygons: bool = False,
        iou_threshold: float = 0.5,
        heatmap_threshold: float = 0.3,
        min_region_area: int = 10,
        image_width: int = 512,
        image_height: int = 512
    ) -> Dict[str, float]:
        """
        Compute F1 score for heatmap predictions against ground truth annotations.
        
        Args:
            pred_heatmap: Predicted heatmap
            gt_data: Ground truth bboxes or polygons
            use_polygons: Whether GT data contains polygons
            iou_threshold: IoU threshold for TP matching
            heatmap_threshold: Threshold for binarizing heatmap
            min_region_area: Minimum area for heatmap regions
            image_width: Image width for scaling
            image_height: Image height for scaling
            
        Returns:
            Dictionary with F1 metrics
        """
        # Extract bounding boxes from heatmap regions
        pred_bboxes = Evaluation._extract_bboxes_from_heatmap(
            pred_heatmap, heatmap_threshold, min_region_area, image_width, image_height
        )
        
        # Use existing F1 computation
        return Evaluation._compute_localization_f1(
            gt_data, pred_bboxes, use_polygons, iou_threshold
        )

    @staticmethod  
    def _compute_heatmap_to_heatmap_f1(
        pred_heatmap: np.ndarray,
        gt_heatmap: np.ndarray,
        iou_threshold: float = 0.5,
        threshold_pred: float = 0.3,
        threshold_gt: float = 0.3,
        min_region_area: int = 10
    ) -> Dict[str, float]:
        """
        Compute F1 score between two heatmaps using connected components.
        
        Args:
            pred_heatmap: Predicted heatmap
            gt_heatmap: Ground truth heatmap
            iou_threshold: IoU threshold for TP matching
            threshold_pred: Threshold for pred heatmap binarization
            threshold_gt: Threshold for GT heatmap binarization
            min_region_area: Minimum area for regions
            
        Returns:
            Dictionary with F1 metrics
        """
        try:
            # Normalize shapes to 2D
            if len(pred_heatmap.shape) == 4:
                pred_heatmap = pred_heatmap[0, 0]
            elif len(pred_heatmap.shape) == 3:
                pred_heatmap = pred_heatmap[:, :, 0]
            if len(gt_heatmap.shape) == 4:
                gt_heatmap = gt_heatmap[0, 0]
            elif len(gt_heatmap.shape) == 3:
                gt_heatmap = gt_heatmap[:, :, 0]

            # Extract regions from both heatmaps
            pred_bin = (pred_heatmap > threshold_pred).astype(np.uint8)
            gt_bin = (gt_heatmap > threshold_gt).astype(np.uint8)

            pred_regions = [r for r in Evaluation._connected_components(pred_bin) if np.sum(r) >= min_region_area]
            gt_regions = [r for r in Evaluation._connected_components(gt_bin) if np.sum(r) >= min_region_area]

            if not gt_regions and not pred_regions:
                return {'tp': 0, 'fp': 0, 'fn': 0, 'precision': 1.0, 'recall': 1.0, 'f1': 1.0}
            if not gt_regions:
                return {'tp': 0, 'fp': len(pred_regions), 'fn': 0, 'precision': 0.0, 'recall': 1.0, 'f1': 0.0}
            if not pred_regions:
                return {'tp': 0, 'fp': 0, 'fn': len(gt_regions), 'precision': 1.0, 'recall': 0.0, 'f1': 0.0}

            # Compute IoU matrix between GT and predicted regions
            iou_matrix = np.zeros((len(gt_regions), len(pred_regions)))
            for i, gt_region in enumerate(gt_regions):
                for j, pred_region in enumerate(pred_regions):
                    iou_matrix[i, j] = Evaluation._mask_iou(gt_region, pred_region)

            # Greedy matching
            matched_predictions = set()
            tp = 0
            
            for gt_idx in range(len(gt_regions)):
                best_iou = 0.0
                best_pred_idx = -1
                
                for pred_idx in range(len(pred_regions)):
                    if pred_idx in matched_predictions:
                        continue
                        
                    iou = iou_matrix[gt_idx, pred_idx]
                    if iou >= iou_threshold and iou > best_iou:
                        best_iou = iou
                        best_pred_idx = pred_idx
                
                if best_pred_idx != -1:
                    matched_predictions.add(best_pred_idx)
                    tp += 1

            fp = len(pred_regions) - len(matched_predictions)
            fn = len(gt_regions) - tp
            
            precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
            recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
            f1 = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0
            
            return {
                'tp': tp,
                'fp': fp,
                'fn': fn, 
                'precision': precision,
                'recall': recall,
                'f1': f1
            }
            
        except Exception:
            return {'tp': 0, 'fp': 0, 'fn': 0, 'precision': 0.0, 'recall': 0.0, 'f1': 0.0}

    def _css_score(self, s1: str, s2: str) -> float:
        """
        Compute cosine similarity score between two text strings.
        
        Args:
            s1: First text string
            s2: Second text string
            
        Returns:
            Cosine similarity score
        """
        if self.css_model is None or util is None:
            return 0.0
            
        emb1 = self.css_model.encode(s1, convert_to_tensor=True)
        emb2 = self.css_model.encode(s2, convert_to_tensor=True)
        
        cosine_sim = util.cos_sim(emb1, emb2).cpu().item()
        return cosine_sim

    def compute_global_caption_scores(self, reference: str, hypothesis: str) -> Tuple[float, float]:
        """
        Compute global text scores (ROUGE-L, CSS) between a reference caption and a predicted caption.

        Args:
            reference: Ground-truth caption text
            hypothesis: Predicted caption text

        Returns:
            Tuple of (rouge_l_f1, css_cosine_similarity)
        """
        rouge_l = 0.0
        css = 0.0
        try:
            if self.rouge_scorer is not None and reference and hypothesis:
                score = self.rouge_scorer.score(reference, hypothesis)
                rouge_l = float(score['rougeL'].fmeasure)
        except Exception:
            rouge_l = 0.0
        try:
            if self.css_model is not None and reference and hypothesis:
                css = float(self._css_score(reference, hypothesis))
        except Exception:
            css = 0.0
        return rouge_l, css

    def get_scores(
        self, 
        ground_data: List[Union[List[float], List[List[float]]]], 
        ground_desc_list: List[str], 
        result_bbox_list: List[List[float]], 
        result_desc_list: List[str],
        use_polygons: bool = False
    ) -> Tuple[float, float, float]:
        """
        Compute evaluation scores for artifact detection results.
        
        Args:
            ground_data: Ground truth bboxes or polygon segmentations
            ground_desc_list: Ground truth descriptions
            result_bbox_list: Predicted bounding boxes
            result_desc_list: Predicted descriptions
            use_polygons: Whether to use polygon-based IoU computation
            
        Returns:
            Tuple of (mean_iou, mean_rouge_l, mean_css)
        """
        rouge_scores = []
        css_scores = []

        iou, mapping = self._match_and_mean_iou(
            ground_data, result_bbox_list, use_polygons
        )

        # Compute text-based scores for matched artifacts
        for gt_idx, est_idx in mapping.items():
            if gt_idx < len(ground_desc_list) and est_idx < len(result_desc_list):
                ref = ground_desc_list[gt_idx]
                hyp = result_desc_list[est_idx]
                
                # ROUGE-L score
                if self.rouge_scorer is not None:
                    score = self.rouge_scorer.score(ref, hyp)
                    rouge_scores.append(score['rougeL'].fmeasure)
                else:
                    rouge_scores.append(0.0)
                
                # Cosine similarity score
                css_scores.append(self._css_score(ref, hyp))

        # Compute mean scores, penalizing unmatched ground truth artifacts
        num_gt = len(ground_desc_list)
        mean_rouge_l = np.sum(rouge_scores) / num_gt if num_gt > 0 else 0.0
        mean_css = np.sum(css_scores) / num_gt if num_gt > 0 else 0.0

        return iou, mean_rouge_l, mean_css

    def generate_statistics(
        self, 
        dataset_type: str,
        eval_type: str,
        json_data: Dict, 
        result: Dict,
        image_size: Optional[Tuple[int, int]] = None,
    ) -> Dict[str, Any]:
        """
        Generate evaluation statistics for a single image.
        
        Args:
            dataset_type: Type of dataset ('synthscars', 'synartifact', 'loki', 'richhf')
            eval_type: Type of evaluation ('binary', 'localization', 'explanation')
            json_data: Ground truth annotation data
            result: Model prediction results
            image_size: Optional tuple of (width, height) for image dimensions
            
        Returns:
            stats dict with keys: binary_success, iou, rouge_l, css, classification,
            has_gt_artifacts, has_pred_artifacts
        """
        img_w, img_h = (image_size if image_size is not None else (512, 512))
        
        # Initialize variables for all paths
        stats = {
            'binary_success': False,
            'iou': 0.0,
            'rouge_l': 0.0,
            'css': 0.0,
            'classification': None,  # Will be 'TP', 'FP', 'FN', or 'TN'
            'has_gt_artifacts': False,
            'has_pred_artifacts': False,
            # Global caption metrics (optional; used for certain datasets)
            'global_rouge_l': 0.0,
            'global_css': 0.0,
            # Localization F1 metrics (for localization task)
            'loc_tp': 0,
            'loc_fp': 0,
            'loc_fn': 0,
            'loc_precision': 0.0,
            'loc_recall': 0.0,
            'loc_f1': 0.0,
        }
        
        # Handle different evaluation types
        if eval_type == 'binary':
            return self._handle_binary_evaluation(dataset_type, json_data, result, stats, img_w, img_h)
        elif eval_type == 'localization':
            return self._handle_localization_evaluation(dataset_type, json_data, result, stats, img_w, img_h)
        elif eval_type == 'explanation':
            return self._handle_explanation_evaluation(dataset_type, json_data, result, stats)
        else:
            raise ValueError(f"Unsupported evaluation type: {eval_type}")
    
    def _handle_binary_evaluation(self, dataset_type: str, json_data: Dict, result: Dict, 
                                  stats: Dict, img_w: int, img_h: int) -> Dict[str, Any]:
        """Handle binary classification evaluation."""
        # Binary evaluation expects True/False response from the model
        predicted_artifacts = result.get('prediction', False)
        
        # Determine ground truth based on dataset
        if dataset_type == 'synartifact':
            # SynArtifact has negative samples
            has_gt_artifacts = bool(json_data.get('Artifacts annotation', []))
            stats['has_gt_artifacts'] = has_gt_artifacts
            print(f"Positive sample?: {has_gt_artifacts}")
        else:
            # Other datasets (synthscars, loki, richhf) typically have only positive samples
            stats['has_gt_artifacts'] = True
            has_gt_artifacts = True
        
        stats['has_pred_artifacts'] = predicted_artifacts
        
        # Classification logic
        if has_gt_artifacts and predicted_artifacts:
            stats['classification'] = 'TP'
            stats['binary_success'] = True
        elif not has_gt_artifacts and not predicted_artifacts:
            stats['classification'] = 'TN'
            stats['binary_success'] = True
        elif has_gt_artifacts and not predicted_artifacts:
            stats['classification'] = 'FN'
            stats['binary_success'] = False
        else:  # not has_gt_artifacts and predicted_artifacts
            stats['classification'] = 'FP'
            stats['binary_success'] = False
            
        return stats
    
    def _handle_localization_evaluation(self, dataset_type: str, json_data: Dict, result: Dict, 
                                        stats: Dict, img_w: int, img_h: int) -> Dict[str, Any]:
        """Handle localization evaluation using threshold-independent IoU."""
        pred_heatmap = None
        if isinstance(result, Dict):
            pred_heatmap = result.get('heatmap', None)

        # Extract prediction data
        result_bbox_list = []
        if len(result) > 0:
            result_bbox_list = [d.get('bbox_2d', []) for d in result if 'bbox_2d' in d]

        # Determine prediction and ground truth types
        pred_type = None
        if pred_heatmap is not None:
            pred_type = 'heatmap'
            pred_data = pred_heatmap
        elif result_bbox_list:
            # Use bbox_list type if we have multiple bboxes, otherwise single bbox
            if len(result_bbox_list) > 1:
                pred_type = 'bbox_list'
                pred_data = result_bbox_list
            else:
                pred_type = 'bbox'
                pred_data = result_bbox_list[0] if result_bbox_list else []
        else:
            # No predictions, set IoU to 0
            stats['iou'] = 0.0
            return stats

        # Compute threshold-independent IoU based on dataset type
        if dataset_type == 'synthscars':
            ground_seg_list = [d['segmentation'][0] for d in json_data['refs'] if 'segmentation' in d]
            
            if ground_seg_list:
                if len(ground_seg_list) > 1:
                    # Multiple segmentations - compute best match IoU
                    gt_type = 'segmentation'
                    max_iou = 0.0
                    for gt_seg in ground_seg_list:
                        iou = self._compute_threshold_independent_iou(
                            pred_data, gt_seg, pred_type, gt_type, img_w, img_h
                        )
                        max_iou = max(max_iou, iou)
                    stats['iou'] = max_iou
                else:
                    # Single segmentation
                    gt_type = 'segmentation'
                    iou = self._compute_threshold_independent_iou(
                        pred_data, ground_seg_list[0], pred_type, gt_type, img_w, img_h
                    )
                    stats['iou'] = iou
            else:
                stats['iou'] = 0.0
                
        elif dataset_type == 'synartifact':
            has_gt_artifacts = json_data.get('Artifacts annotation', [])
            
            if has_gt_artifacts:
                # Only compute localization metrics for positive samples (samples with artifacts)
                ground_bbox_list = []
                for annotation in has_gt_artifacts:
                    if 'rect_start' in annotation and 'rect_end' in annotation:
                        bbox = annotation['rect_start'] + annotation['rect_end']
                        ground_bbox_list.append(bbox)
                
                if ground_bbox_list:
                    if len(ground_bbox_list) > 1:
                        # Multiple GT bboxes - use bbox_list for optimal matching
                        gt_type = 'bbox_list'
                        iou = self._compute_threshold_independent_iou(
                            pred_data, ground_bbox_list, pred_type, gt_type, img_w, img_h
                        )
                        stats['iou'] = iou
                    else:
                        # Single GT bbox
                        gt_type = 'bbox'
                        iou = self._compute_threshold_independent_iou(
                            pred_data, ground_bbox_list[0], pred_type, gt_type, img_w, img_h
                        )
                        stats['iou'] = iou
                else:
                    stats['iou'] = 0.0
            else:
                # Skip negative samples (samples without artifacts) for localization evaluation
                # Mark IoU as None so it can be filtered out during aggregation
                stats['iou'] = None
                    
        elif dataset_type == 'loki':
            regional_problems = json_data['problems']['regional']
            ground_bbox_list = []
            
            for problem in regional_problems:
                if 'region' in problem:
                    x, y, w, h = problem['region']
                    bbox = [x, y, x + w, y + h]
                    ground_bbox_list.append(bbox)
            
            if ground_bbox_list:
                if len(ground_bbox_list) > 1:
                    # Multiple GT bboxes - use bbox_list for optimal matching
                    gt_type = 'bbox_list'
                    iou = self._compute_threshold_independent_iou(
                        pred_data, ground_bbox_list, pred_type, gt_type, img_w, img_h
                    )
                    stats['iou'] = iou
                else:
                    # Single GT bbox
                    gt_type = 'bbox'
                    iou = self._compute_threshold_independent_iou(
                        pred_data, ground_bbox_list[0], pred_type, gt_type, img_w, img_h
                    )
                    stats['iou'] = iou
            else:
                stats['iou'] = 0.0
                
        elif dataset_type == 'richhf':
            artifact_map_path = "/home/jovyan/image-artifacts/data/richhf-18k/" + json_data['artifact_map_path']
            artifact_map = np.load(artifact_map_path)
            gt_type = 'heatmap'
            
            try:
                stats['iou'] = self._compute_threshold_independent_iou(
                    pred_data, artifact_map, pred_type, gt_type, img_w, img_h
                )
            except Exception:
                stats['iou'] = 0.0
        
        return stats
    
