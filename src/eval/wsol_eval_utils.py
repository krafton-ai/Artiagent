    @staticmethod
    def _compute_iou(boxA: List[float], boxB: List[float]) -> float:
        """
        Compute the Intersection over Union (IoU) of two bounding boxes.
        
        Args:
            boxA: Bounding box in format [x1, y1, x2, y2]
            boxB: Bounding box in format [x1, y1, x2, y2]
            
        Returns:
            IoU score between 0 and 1
        """
        # Determine intersection coordinates
        xA = max(boxA[0], boxB[0])
        yA = max(boxA[1], boxB[1])
        xB = min(boxA[2], boxB[2])
        yB = min(boxA[3], boxB[3])

        # Compute intersection area
        interW = max(0, xB - xA)
        interH = max(0, yB - yA)
        interArea = interW * interH

        if interArea == 0:
            return 0.0

        # Compute union area
        boxAArea = (boxA[2] - boxA[0]) * (boxA[3] - boxA[1])
        boxBArea = (boxB[2] - boxB[0]) * (boxB[3] - boxB[1])
        unionArea = boxAArea + boxBArea - interArea
        
        return interArea / float(unionArea) if unionArea > 0 else 0.0

    @staticmethod
    def _compute_iou_polygon(seg: List[float], bbox: List[float]) -> float:
        """
        Compute the Intersection over Union (IoU) of a polygonal segmentation and a bbox.
        
        Args:
            seg: Polygon coordinates as flat list [x1, y1, x2, y2, ..., xn, yn]
            bbox: Bounding box in format [x1, y1, x2, y2]
            
        Returns:
            IoU score between 0 and 1
        """
        try:
            if Polygon is None or box is None:
                # Shapely not available, fallback to 0
                return 0.0
                
            # Convert flat coordinates to point pairs
            poly_points = [(seg[i], seg[i+1]) for i in range(0, len(seg), 2)]
            
            # Create Shapely polygons
            seg_poly = Polygon(poly_points)
            x1, y1, x2, y2 = bbox
            bbox_poly = box(x1, y1, x2, y2)
            
            # Compute intersection and union
            intersection = seg_poly.intersection(bbox_poly).area
            union = seg_poly.union(bbox_poly).area
            
            return intersection / union if union > 0 else 0.0
            
        except Exception:
            # Fallback to 0 if polygon operations fail
            return 0.0

    @staticmethod
    def _normalize_heatmap(heatmap: np.ndarray) -> np.ndarray:
        """
        Per-image min-max normalization of heatmap as described in the reference paper.
        
        Args:
            heatmap: Input heatmap array
            
        Returns:
            Normalized heatmap with values between 0 and 1
        """
        # Ensure 2D
        if len(heatmap.shape) == 4:
            heatmap = heatmap[0, 0]
        elif len(heatmap.shape) == 3:
            heatmap = heatmap[:, :, 0]
            
        # Min-max normalization
        min_val = np.min(heatmap)
        max_val = np.max(heatmap)
        
        if max_val - min_val > 0:
            normalized = (heatmap - min_val) / (max_val - min_val)
        else:
            normalized = np.zeros_like(heatmap)
            
        return normalized.astype(np.float32)
    
    @staticmethod
    def _heatmap_to_tightest_bbox(heatmap: np.ndarray, threshold: float, image_width: int, image_height: int) -> List[float]:
        """
        Convert heatmap to tightest bounding box using threshold.
        
        Args:
            heatmap: Normalized heatmap
            threshold: Threshold value
            image_width: Width for scaling coordinates
            image_height: Height for scaling coordinates
            
        Returns:
            Bounding box in format [x1, y1, x2, y2], empty list if no regions found
        """
        # Threshold heatmap
        binary_mask = (heatmap > threshold).astype(np.uint8)
        
        # Find coordinates of positive pixels
        coords = np.where(binary_mask > 0)
        if len(coords[0]) == 0:
            return []
            
        # Get bounding box
        y_min, y_max = np.min(coords[0]), np.max(coords[0])
        x_min, x_max = np.min(coords[1]), np.max(coords[1])
        
        # Scale to image coordinates
        h, w = heatmap.shape
        x1 = (x_min / w) * image_width
        y1 = (y_min / h) * image_height
        x2 = (x_max / w) * image_width  
        y2 = (y_max / h) * image_height
        
        return [x1, y1, x2, y2]
    
    @staticmethod
    def _compute_threshold_independent_iou(
        pred_data: Any,
        gt_data: Any, 
        pred_type: str,
        gt_type: str,
        image_width: int,
        image_height: int,
        num_thresholds: int = 100
    ) -> float:
        """
        Compute threshold-independent IoU following the reference paper rules.
        
        Supports all combinations of representation types with optimal matching:
        - Single representations: heatmap, bbox, segmentation
        - Multiple representations: bbox_list, segmentation_list
        - Mixed combinations: e.g., heatmap vs bbox_list, segmentation_list vs bbox
        
        Args:
            pred_data: Prediction data (heatmap, bbox, bbox_list, segmentation, segmentation_list)
            gt_data: Ground truth data (heatmap, bbox, bbox_list, segmentation, segmentation_list)  
            pred_type: Type of prediction ('heatmap', 'bbox', 'bbox_list', 'segmentation', 'segmentation_list')
            gt_type: Type of ground truth ('heatmap', 'bbox', 'bbox_list', 'segmentation', 'segmentation_list')
            image_width: Image width
            image_height: Image height
            num_thresholds: Number of thresholds to sweep for heatmaps
            
        Returns:
            Maximum IoU across all thresholds and optimal region matching
        """
        thresholds = np.linspace(0.0, 1.0, num_thresholds)
        max_iou = 0.0
        
        # Handle different combinations according to the rules
        if pred_type == 'heatmap' and gt_type == 'heatmap':
            # Heatmap vs. Heatmap: pixelwise mIoU
            pred_norm = Evaluation._normalize_heatmap(pred_data)
            gt_norm = Evaluation._normalize_heatmap(gt_data)
            
            for tau in thresholds:
                pred_binary = (pred_norm > tau).astype(np.uint8)
                gt_binary = (gt_norm > tau).astype(np.uint8)
                
                intersection = np.sum((pred_binary == 1) & (gt_binary == 1))
                union = np.sum((pred_binary == 1) | (gt_binary == 1))
                
                if union > 0:
                    iou = intersection / union
                    max_iou = max(max_iou, iou)
                    
        elif pred_type == 'heatmap' and gt_type == 'bbox':
            # Heatmap vs. Bbox: approximate heatmap into tightest bbox with thresholding
            pred_norm = Evaluation._normalize_heatmap(pred_data)
            
            for tau in thresholds:
                pred_bbox = Evaluation._heatmap_to_tightest_bbox(pred_norm, tau, image_width, image_height)
                if pred_bbox:
                    iou = Evaluation._compute_iou(pred_bbox, gt_data)
                    max_iou = max(max_iou, iou)
                    
        elif pred_type == 'bbox' and gt_type == 'heatmap':
            # Bbox vs. Heatmap: approximate heatmap into tightest bbox with thresholding
            gt_norm = Evaluation._normalize_heatmap(gt_data)
            
            for tau in thresholds:
                gt_bbox = Evaluation._heatmap_to_tightest_bbox(gt_norm, tau, image_width, image_height)
                if gt_bbox:
                    iou = Evaluation._compute_iou(pred_data, gt_bbox)
                    max_iou = max(max_iou, iou)
                    
        elif pred_type == 'heatmap' and gt_type == 'segmentation':
            # Heatmap vs. Segmentation map: segmentation map into binary map
            pred_norm = Evaluation._normalize_heatmap(pred_data)
            
            # Convert segmentation to binary mask
            gt_binary = np.zeros((image_height, image_width), dtype=np.uint8)
            if len(gt_data) >= 6:  # At least 3 points for polygon
                points = [(int(gt_data[i]), int(gt_data[i+1])) for i in range(0, len(gt_data), 2)]
                img = Image.new('L', (image_width, image_height), 0)
                draw = ImageDraw.Draw(img)
                draw.polygon(points, outline=1, fill=1)
                gt_binary = np.array(img)
            
            for tau in thresholds:
                # Resize pred_norm to match image dimensions if needed
                if pred_norm.shape != (image_height, image_width):
                    pred_img = Image.fromarray((pred_norm * 255).astype(np.uint8))
                    pred_img = pred_img.resize((image_width, image_height), Image.LANCZOS)
                    pred_resized = np.array(pred_img).astype(np.float32) / 255.0
                else:
                    pred_resized = pred_norm
                    
                pred_binary = (pred_resized > tau).astype(np.uint8)
                
                intersection = np.sum((pred_binary == 1) & (gt_binary == 1))
                union = np.sum((pred_binary == 1) | (gt_binary == 1))
                
                if union > 0:
                    iou = intersection / union
                    max_iou = max(max_iou, iou)
                    
        elif pred_type == 'bbox' and gt_type == 'bbox':
            # Bbox vs. Bbox: IoU
            max_iou = Evaluation._compute_iou(pred_data, gt_data)
            
        elif pred_type == 'bbox' and gt_type == 'segmentation':
            # Bbox vs. Segmentation: compute polygon-bbox IoU
            max_iou = Evaluation._compute_iou_polygon(gt_data, pred_data)
            
        elif pred_type == 'segmentation' and gt_type == 'bbox':
            # Segmentation vs. Bbox: compute polygon-bbox IoU
            max_iou = Evaluation._compute_iou_polygon(pred_data, gt_data)
            
        elif pred_type == 'segmentation' and gt_type == 'segmentation':
            # Segmentation vs. Segmentation: polygon-polygon IoU
            max_iou = Evaluation._compute_iou_polygon(pred_data, gt_data)
            
        elif pred_type == 'heatmap' and gt_type == 'segmentation_list':
            # Heatmap vs. Multiple GT segmentations: sweep thresholds for each segmentation
            pred_norm = Evaluation._normalize_heatmap(pred_data)
            max_iou = 0.0
            
            for tau in thresholds:
                pred_bbox = Evaluation._heatmap_to_tightest_bbox(pred_norm, tau, image_width, image_height)
                if pred_bbox:
                    for gt_seg in gt_data:
                        if gt_seg and len(gt_seg) >= 6:
                            iou = Evaluation._compute_iou_polygon(gt_seg, pred_bbox)
                            max_iou = max(max_iou, iou)
        
        elif pred_type == 'segmentation_list' and gt_type == 'heatmap':
            # Multiple predicted segmentations vs. GT heatmap: normalize heatmap and find best match
            gt_norm = Evaluation._normalize_heatmap(gt_data)
            max_iou = 0.0
            
            for tau in thresholds:
                gt_bbox = Evaluation._heatmap_to_tightest_bbox(gt_norm, tau, image_width, image_height)
                if gt_bbox:
                    for pred_seg in pred_data:
                        if pred_seg and len(pred_seg) >= 6:
                            iou = Evaluation._compute_iou_polygon(pred_seg, gt_bbox)
                            max_iou = max(max_iou, iou)
        
        # Handle segmentation lists
        elif pred_type == 'segmentation_list' or gt_type == 'segmentation_list':
            max_iou = Evaluation._compute_multi_segmentation_iou(pred_data, gt_data, pred_type, gt_type)
            
        # Handle multiple bbox cases
        elif pred_type == 'bbox_list' or gt_type == 'bbox_list':
            max_iou = Evaluation._compute_multi_bbox_iou(pred_data, gt_data, pred_type, gt_type)
            
        return max_iou

    @staticmethod
    def _compute_multi_bbox_iou(
        pred_data: Any,
        gt_data: Any,
        pred_type: str,
        gt_type: str
    ) -> float:
        """
        Compute IoU for cases involving multiple bounding boxes.
        
        Args:
            pred_data: Prediction data (bbox list or single bbox/heatmap/segmentation)
            gt_data: Ground truth data (bbox list or single bbox/heatmap/segmentation)
            pred_type: Type of prediction ('bbox_list', 'bbox', 'heatmap', 'segmentation')
            gt_type: Type of ground truth ('bbox_list', 'bbox', 'heatmap', 'segmentation')
            
        Returns:
            Maximum IoU computed using optimal matching between regions
        """
        if pred_type == 'bbox_list' and gt_type == 'bbox_list':
            # Multiple bboxes vs. Multiple bboxes: use optimal matching
            if not pred_data or not gt_data:
                return 0.0
            
            # Filter out invalid bboxes
            valid_pred_bboxes = [bbox for bbox in pred_data if bbox and len(bbox) >= 4]
            valid_gt_bboxes = [bbox for bbox in gt_data if bbox and len(bbox) >= 4]
            
            if not valid_pred_bboxes or not valid_gt_bboxes:
                return 0.0
            
            # Use multi-region IoU computation for optimal matching
            return Evaluation._compute_multi_region_iou(valid_pred_bboxes, valid_gt_bboxes, use_polygons=False)
            
        elif pred_type == 'bbox_list' and gt_type == 'bbox':
            # Multiple predicted bboxes vs. Single GT bbox: best match
            if not pred_data:
                return 0.0
            
            max_iou = 0.0
            for pred_bbox in pred_data:
                if not pred_bbox or len(pred_bbox) < 4:
                    continue
                iou = Evaluation._compute_iou(pred_bbox, gt_data)
                max_iou = max(max_iou, iou)
            return max_iou
            
        elif pred_type == 'bbox' and gt_type == 'bbox_list':
            # Single predicted bbox vs. Multiple GT bboxes: best match
            if not gt_data:
                return 0.0
                
            max_iou = 0.0
            for gt_bbox in gt_data:
                if not gt_bbox or len(gt_bbox) < 4:
                    continue
                iou = Evaluation._compute_iou(pred_data, gt_bbox)
                max_iou = max(max_iou, iou)
            return max_iou
            
        elif pred_type == 'bbox_list' and gt_type == 'segmentation':
            # Multiple predicted bboxes vs. Segmentation: best match
            if not pred_data:
                return 0.0
                
            max_iou = 0.0
            for pred_bbox in pred_data:
                if not pred_bbox or len(pred_bbox) < 4:
                    continue
                iou = Evaluation._compute_iou_polygon(gt_data, pred_bbox)
                max_iou = max(max_iou, iou)
            return max_iou
            
        elif pred_type == 'segmentation' and gt_type == 'bbox_list':
            # Segmentation vs. Multiple GT bboxes: best match
            if not gt_data:
                return 0.0
                
            max_iou = 0.0
            for gt_bbox in gt_data:
                if not gt_bbox or len(gt_bbox) < 4:
                    continue
                iou = Evaluation._compute_iou_polygon(pred_data, gt_bbox)
                max_iou = max(max_iou, iou)
            return max_iou
            
        elif pred_type == 'heatmap' and gt_type == 'bbox_list':
            # Heatmap vs. Multiple GT bboxes: extract best bbox from heatmap and match
            if not gt_data:
                return 0.0
                
            pred_norm = Evaluation._normalize_heatmap(pred_data)
            max_iou = 0.0
            
            # Use different thresholds to extract bbox from heatmap
            thresholds = np.linspace(0.0, 1.0, 100)
            for tau in thresholds:
                pred_bbox = Evaluation._heatmap_to_tightest_bbox(pred_norm, tau, 512, 512)  # Default image size
                if pred_bbox:
                    for gt_bbox in gt_data:
                        if not gt_bbox or len(gt_bbox) < 4:
                            continue
                        iou = Evaluation._compute_iou(pred_bbox, gt_bbox)
                        max_iou = max(max_iou, iou)
            return max_iou
            
        elif pred_type == 'bbox_list' and gt_type == 'heatmap':
            # Multiple predicted bboxes vs. Heatmap: extract best bbox from heatmap and match
            if not pred_data:
                return 0.0
                
            gt_norm = Evaluation._normalize_heatmap(gt_data)
            max_iou = 0.0
            
            # Use different thresholds to extract bbox from heatmap
            thresholds = np.linspace(0.0, 1.0, 100)
            for tau in thresholds:
                gt_bbox = Evaluation._heatmap_to_tightest_bbox(gt_norm, tau, 512, 512)  # Default image size
                if gt_bbox:
                    for pred_bbox in pred_data:
                        if not pred_bbox or len(pred_bbox) < 4:
                            continue
                        iou = Evaluation._compute_iou(pred_bbox, gt_bbox)
                        max_iou = max(max_iou, iou)
            return max_iou
            
        else:
            # Fallback for unsupported combinations
            return 0.0

