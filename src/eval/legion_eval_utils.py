    def _handle_binary_evaluation(self, dataset_type: str, json_data: Dict, result: Dict, 
                                  stats: Dict, img_w: int, img_h: int) -> Dict[str, Any]:
        """Handle binary classification evaluation."""
        # Binary evaluation expects True/False response from the model
        predicted_artifacts = result.get('prediction', False)
        
        # Determine ground truth based on dataset
        if dataset_type == 'synartifact':
            # SynArtifact has negative samples
            has_gt_artifacts = bool(json_data.get('Artifacts annotation', []))
            stats['has_gt_artifacts'] = has_gt_artifacts
        else:
            # Other datasets (synthscars, loki, richhf) typically have only positive samples
            stats['has_gt_artifacts'] = True
            has_gt_artifacts = True
        
        stats['has_pred_artifacts'] = predicted_artifacts
        
        # Classification logic
        if has_gt_artifacts and predicted_artifacts:
            stats['classification'] = 'TP'
            stats['binary_success'] = True
        elif not has_gt_artifacts and not predicted_artifacts:
            stats['classification'] = 'TN'
            stats['binary_success'] = True
        elif has_gt_artifacts and not predicted_artifacts:
            stats['classification'] = 'FN'
            stats['binary_success'] = False
        else:  # not has_gt_artifacts and predicted_artifacts
            stats['classification'] = 'FP'
            stats['binary_success'] = False
            
        return stats
    
    def _handle_localization_evaluation(self, dataset_type: str, json_data: Dict, result: Dict, 
                                        stats: Dict, img_w: int, img_h: int) -> Dict[str, Any]:
        """Handle localization evaluation - return only mean IoU."""
        pred_heatmap = None
        if isinstance(result, Dict):
            pred_heatmap = result.get('heatmap', None)
            pred_heatmap = self._binarize_heatmap(pred_heatmap)

