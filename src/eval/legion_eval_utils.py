    @staticmethod
    def compute_f1_metrics(results: Dict[int, Dict]) -> Dict:
        """
        Compute F1, precision, recall from detailed evaluation results.
        
        Args:
            results: List of detailed evaluation results
            
        Returns:
            Dictionary with F1 metrics and TP/FP/FN/TN counts
        """
        tp = sum(1 for _, r in results.items() if r.get('classification') == 'TP')
        fp = sum(1 for _, r in results.items() if r.get('classification') == 'FP')
        fn = sum(1 for _, r in results.items() if r.get('classification') == 'FN')
        tn = sum(1 for _, r in results.items() if r.get('classification') == 'TN')
        
        # Compute precision, recall, F1
        precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
        recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
        f1_positive = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0
        
        precision_negative = tn / (tn + fn) if (tn + fn) > 0 else 0.0
        recall_negative = tn / (tn + fp) if (tn + fp) > 0 else 0.0
        f1_negative = 2 * (precision_negative * recall_negative) / (precision_negative + recall_negative) if (precision_negative + recall_negative) > 0 else 0.0
        
        # Macro F1 is the average of F1 scores for both classes
        macro_f1 = (f1_positive + f1_negative) / 2.0

        # Compute accuracy
        accuracy = (tp + tn) / len(results) if len(results) > 0 else 0.0

        return {
            'tp': tp,
            'fp': fp,
            'fn': fn,
            'tn': tn,
            'precision': precision,
            'recall': recall,
            'macro_f1': macro_f1,
            'f1_positive': f1_positive,
            'f1_negative': f1_negative,
            'precision_negative': precision_negative,
            'recall_negative': recall_negative,
            'accuracy': accuracy
        }