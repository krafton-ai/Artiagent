def parse_json(response: str):
    """
    Try to extract valid JSON (object or array) from a response string that may include 
    markdown fences, incomplete JSON, or trailing commas.
    Returns the parsed Python object, or raises a ValueError if it can't.
    """
    if not isinstance(response, str):
        raise ValueError(f"Expected string input, got {type(response)}: {response}")
    
    # 1) Strip markdown fences ```json ... ``` or ```python ... ```
    cleaned = re.sub(r"```(?:json|python)?\s*", "", response)
    cleaned = re.sub(r"\s*```", "", cleaned).strip()
    
    # 2) Try to find the JSON content (object or array)
    json_content = None
    obj_match = re.search(r'\{.*\}', cleaned, re.DOTALL)
    arr_match = re.search(r'\[.*\]', cleaned, re.DOTALL)

    # Prefer array if found, otherwise object
    if arr_match:
        json_content = arr_match.group()
    elif obj_match:
        json_content = obj_match.group()
    else:
        json_content = cleaned

    # 3) Clean up common issues (e.g., trailing commas)
    json_content = re.sub(r",\s*([\]}])", r"\1", json_content)
    json_content = json_content.strip()

    # 4) Try to parse JSON directly
    try:
        return json.loads(json_content)
    except json.JSONDecodeError as e:
        # Try fixing common JSON issues and retry
        try:
            fixed = re.sub(r"\b(true|false|null)\b", lambda m: f'"{m.group(1)}"', json_content)
            fixed = re.sub(r'"(true|false|null)"', lambda m: m.group(1), fixed)
            return json.loads(fixed)
        except json.JSONDecodeError:
            pass

        raise ValueError(f"Failed to decode JSON from response. Original error: {e}\nContent: {json_content!r}\nFull response: {response!r}")

class Evaluation:
    """
    Provides utilities for evaluating artifact detection performance.
    
    This class computes various metrics including IoU, ROUGE-L scores,
    and cosine similarity scores for artifact detection evaluation.
    """
    
    def __init__(self):
        """Initialize evaluation metrics."""
        if SentenceTransformer is not None:
            self.css_model = SentenceTransformer('sentence-transformers/paraphrase-MiniLM-L6-v2')
        else:
            self.css_model = None
            
        if rouge_scorer is not None:
            self.rouge_scorer = rouge_scorer.RougeScorer(['rouge1', 'rougeL'], use_stemmer=True)
        else:
            self.rouge_scorer = None

    @staticmethod
    def _binarize_heatmap(artifact_map: Optional[np.ndarray], threshold: float = 0.3) -> Optional[np.ndarray]:
        """Binarize a heatmap with a threshold. Ensures 2D array output."""
        if artifact_map is None:
            return None
        try:
            arr_map = artifact_map
            if isinstance(arr_map, list):
                arr_map = np.array(arr_map)
            # Handle tensor-like objects with detach method
            if hasattr(arr_map, 'detach'):
                arr_map = arr_map.detach().cpu().numpy()  # type: ignore
            
            # Ensure we have a numpy array at this point
            if not isinstance(arr_map, np.ndarray):
                return None
                
            if len(arr_map.shape) == 4:
                # e.g., (1,1,512,512)
                arr_map = arr_map[0, 0]
            elif len(arr_map.shape) == 3:
                arr_map = arr_map[:, :, 0]
            # Normalize if the values look like logits
            arr = arr_map.astype(np.float32)
            # Thresholding
            binary = (arr > threshold).astype(np.uint8)
            return binary
        except Exception:
            return None

    @staticmethod
    def _convert_to_binary_mask(
        data: Any, 
        mask_type: str,
        image_width: int, 
        image_height: int,
        threshold: float = 0.3
    ) -> np.ndarray:
        """
        Convert various annotation formats to binary mask.
        
        Args:
            data: Ground truth or prediction data
            mask_type: Type of data ('polygon', 'bbox', 'heatmap', 'bbox_list')
            image_width: Image width
            image_height: Image height  
            threshold: Threshold for heatmap binarization
            
        Returns:
            Binary mask with 1 for artifact pixels, 0 for background
        """
        mask = np.zeros((image_height, image_width), dtype=np.uint8)
        
        if mask_type == 'polygon':
            # data is polygon segmentation [x1,y1,x2,y2,...,xn,yn]
            if len(data) >= 6:  # At least 3 points
                points = [(int(data[i]), int(data[i+1])) for i in range(0, len(data), 2)]
                # Use PIL to rasterize polygon
                img = Image.new('L', (image_width, image_height), 0)
                draw = ImageDraw.Draw(img)
                draw.polygon(points, outline=1, fill=1)
                mask = np.array(img)
                
        elif mask_type == 'bbox':
            # data is bounding box [x1, y1, x2, y2]
            if len(data) == 4:
                x1, y1, x2, y2 = [int(coord) for coord in data]
                x1, x2 = max(0, x1), min(image_width-1, x2)
                y1, y2 = max(0, y1), min(image_height-1, y2)
                if x2 > x1 and y2 > y1:
                    mask[y1:y2+1, x1:x2+1] = 1
                    
        elif mask_type == 'bbox_list':
            # data is list of bounding boxes
            for bbox in data:
                if len(bbox) == 4:
                    x1, y1, x2, y2 = [int(coord) for coord in bbox]
                    x1, x2 = max(0, x1), min(image_width-1, x2)
                    y1, y2 = max(0, y1), min(image_height-1, y2) 
                    if x2 > x1 and y2 > y1:
                        mask[y1:y2+1, x1:x2+1] = 1
                        
        elif mask_type == 'heatmap':
            # data is heatmap array
            heatmap = data
            if hasattr(heatmap, 'detach'):
                heatmap = heatmap.detach().cpu().numpy()  # type: ignore
            if isinstance(heatmap, list):
                heatmap = np.array(heatmap)
                
            # Normalize to 2D
            if len(heatmap.shape) == 4:
                heatmap = heatmap[0, 0]
            elif len(heatmap.shape) == 3:
                heatmap = heatmap[:, :, 0]
                
            # Resize to match image dimensions if needed
            if heatmap.shape != (image_height, image_width):
                from PIL import Image as PILImage
                heatmap_img = PILImage.fromarray((heatmap * 255).astype(np.uint8))
                heatmap_img = heatmap_img.resize((image_width, image_height), PILImage.LANCZOS)
                heatmap = np.array(heatmap_img).astype(np.float32) / 255.0
                
            mask = (heatmap > threshold).astype(np.uint8)
            
        return mask

    @staticmethod
    def _compute_pixel_level_metrics(
        pred_mask: np.ndarray, 
        gt_mask: np.ndarray
    ) -> Dict[str, float]:
        """
        Compute pixel-level segmentation metrics following the paper's methodology.
        
        Args:
            pred_mask: Predicted binary mask (0=background, 1=foreground/artifact)
            gt_mask: Ground truth binary mask (0=background, 1=foreground/artifact)
            
        Returns:
            Dictionary with mIoU, IoU_foreground, IoU_background, F1, precision, recall
        """
        # Flatten masks for easier computation
        pred_flat = pred_mask.flatten()
        gt_flat = gt_mask.flatten()
        f1 = metrics.f1_score(gt_flat, pred_flat, average='binary')

        # Compute confusion matrix elements
        tp = np.sum((pred_flat == 1) & (gt_flat == 1))  # True positive pixels
        tn = np.sum((pred_flat == 0) & (gt_flat == 0))  # True negative pixels  
        fp = np.sum((pred_flat == 1) & (gt_flat == 0))  # False positive pixels
        fn = np.sum((pred_flat == 0) & (gt_flat == 1))  # False negative pixels
        
        # IoU for foreground (artifact class)
        if tp + fp + fn > 0:
            iou_foreground = tp / (tp + fp + fn)
        else:
            # No artifacts in GT or predictions
            iou_foreground = 1.0 if tp == 0 and fp == 0 and fn == 0 else 0.0
            
        # IoU for background (non-artifact class)  
        if tn + fp + fn > 0:
            iou_background = tn / (tn + fp + fn)
        else:
            # This should rarely happen unless image is all artifacts
            iou_background = 1.0 if tn == 0 and fp == 0 and fn == 0 else 0.0
        
        # Mean IoU
        miou = (iou_foreground + iou_background) / 2.0
        
        # Pixel-level F1, precision, recall
        if tp + fp > 0:
            precision = tp / (tp + fp)
        else:
            precision = 1.0 if tp == 0 and fp == 0 else 0.0
            
        if tp + fn > 0:
            recall = tp / (tp + fn)
        else:
            recall = 1.0 if tp == 0 and fn == 0 else 0.0
            
        return {
            'miou': miou,
            'iou_foreground': iou_foreground, 
            'iou_background': iou_background,
            'pixel_f1': f1,
            'pixel_precision': precision,
            'pixel_recall': recall,
            'tp_pixels': int(tp),
            'tn_pixels': int(tn),
            'fp_pixels': int(fp), 
            'fn_pixels': int(fn)
        }

    def _css_score(self, s1: str, s2: str) -> float:
        """
        Compute cosine similarity score between two text strings.
        
        Args:
            s1: First text string
            s2: Second text string
            
        Returns:
            Cosine similarity score
        """
        if self.css_model is None or util is None:
            return 0.0
            
        emb1 = self.css_model.encode(s1, convert_to_tensor=True)
        emb2 = self.css_model.encode(s2, convert_to_tensor=True)
        
        cosine_sim = util.cos_sim(emb1, emb2).cpu().item()
        return cosine_sim

    def compute_global_caption_scores(self, reference: str, hypothesis: str) -> Tuple[float, float]:
        """
        Compute global text scores (ROUGE-L, CSS) between a reference caption and a predicted caption.

        Args:
            reference: Ground-truth caption text
            hypothesis: Predicted caption text

        Returns:
            Tuple of (rouge_l_f1, css_cosine_similarity)
        """
        rouge_l = 0.0
        css = 0.0
        try:
            if self.rouge_scorer is not None and reference and hypothesis:
                score = self.rouge_scorer.score(reference, hypothesis)
                rouge_l = float(score['rougeL'].fmeasure)
        except Exception:
            rouge_l = 0.0
        try:
            if self.css_model is not None and reference and hypothesis:
                css = float(self._css_score(reference, hypothesis))
        except Exception:
            css = 0.0
        return rouge_l, css

    def generate_statistics(
        self, 
        dataset_type: str,
        eval_type: str,
        json_data: Dict, 
        result: Dict,
        image_size: Optional[Tuple[int, int]] = None,
    ) -> Dict[str, Any]:
        """
        Generate evaluation statistics for a single image.
        
        Args:
            dataset_type: Type of dataset ('synthscars', 'synartifact', 'loki', 'richhf')
            eval_type: Type of evaluation ('binary', 'localization', 'explanation')
            json_data: Ground truth annotation data
            result: Model prediction results
            image_size: Optional tuple of (width, height) for image dimensions
            
        Returns:
            stats dict with keys: binary_success, iou, rouge_l, css, classification,
            has_gt_artifacts, has_pred_artifacts
        """
        img_w, img_h = (image_size if image_size is not None else (512, 512))
        
        # Initialize variables for all paths
        stats = {
            'binary_success': False,
            'iou': 0.0,
            'rouge_l': 0.0,
            'css': 0.0,
            'classification': None,  # Will be 'TP', 'FP', 'FN', or 'TN'
            'has_gt_artifacts': False,
            'has_pred_artifacts': False,
            # Global caption metrics (optional; used for certain datasets)
            'global_rouge_l': 0.0,
            'global_css': 0.0,
            # Paper-style pixel-level segmentation metrics
            'miou': 0.0,
            'iou_foreground': 0.0,
            'iou_background': 0.0,
            'pixel_f1': 0.0,
            'pixel_precision': 0.0,
            'pixel_recall': 0.0,
            'tp_pixels': 0,
            'tn_pixels': 0,
            'fp_pixels': 0,
            'fn_pixels': 0,
        }
        
        # Handle different evaluation types
        if eval_type == 'binary':
            return self._handle_binary_evaluation(dataset_type, json_data, result, stats, img_w, img_h)
        elif eval_type == 'localization':
            return self._handle_localization_evaluation(dataset_type, json_data, result, stats, img_w, img_h)
        elif eval_type == 'explanation':
            return self._handle_explanation_evaluation(dataset_type, json_data, result, stats)
        else:
            raise ValueError(f"Unsupported evaluation type: {eval_type}")
    
    def _handle_binary_evaluation(self, dataset_type: str, json_data: Dict, result: Dict, 
                                  stats: Dict, img_w: int, img_h: int) -> Dict[str, Any]:
        """Handle binary classification evaluation."""
        # Binary evaluation expects True/False response from the model
        predicted_artifacts = result.get('prediction', False)
        
        # Determine ground truth based on dataset
        if dataset_type == 'synartifact':
            # SynArtifact has negative samples
            has_gt_artifacts = bool(json_data.get('Artifacts annotation', []))
            stats['has_gt_artifacts'] = has_gt_artifacts
        else:
            # Other datasets (synthscars, loki, richhf) typically have only positive samples
            stats['has_gt_artifacts'] = True
            has_gt_artifacts = True
        
        stats['has_pred_artifacts'] = predicted_artifacts
        
        # Classification logic
        if has_gt_artifacts and predicted_artifacts:
            stats['classification'] = 'TP'
            stats['binary_success'] = True
        elif not has_gt_artifacts and not predicted_artifacts:
            stats['classification'] = 'TN'
            stats['binary_success'] = True
        elif has_gt_artifacts and not predicted_artifacts:
            stats['classification'] = 'FN'
            stats['binary_success'] = False
        else:  # not has_gt_artifacts and predicted_artifacts
            stats['classification'] = 'FP'
            stats['binary_success'] = False
            
        return stats
    
    def _handle_localization_evaluation(self, dataset_type: str, json_data: Dict, result: Dict, 
                                        stats: Dict, img_w: int, img_h: int) -> Dict[str, Any]:
        """Handle localization evaluation - return only mean IoU."""
        pred_heatmap = None
        if isinstance(result, Dict):
            pred_heatmap = result.get('heatmap', None)
            pred_heatmap = self._binarize_heatmap(pred_heatmap)

        # Extract prediction data
        result_bbox_list = []
        if len(result) > 0:
            if isinstance(result[0], List):
                result_bbox_list = result
            else:
                result_bbox_list = [d.get('bbox_2d', []) for d in result if 'bbox_2d' in d]

        # Compute IoU and F1 based on dataset type
        if dataset_type == 'synthscars':
            ground_seg_list = [d['segmentation'][0] for d in json_data['refs'] if 'segmentation' in d]
            # Convert ground truth polygons to binary mask
            gt_mask = np.zeros((img_h, img_w), dtype=np.uint8)
            for seg in ground_seg_list:
                seg_mask = self._convert_to_binary_mask(seg, 'polygon', img_w, img_h)
                gt_mask = np.logical_or(gt_mask, seg_mask).astype(np.uint8)
            
            # Convert predictions to binary mask
            if pred_heatmap is not None:
                pred_mask = self._convert_to_binary_mask(pred_heatmap, 'heatmap', img_w, img_h)
            
            elif result_bbox_list:
                pred_mask = self._convert_to_binary_mask(result_bbox_list, 'bbox_list', img_w, img_h)
            else:
                pred_mask = np.zeros((img_h, img_w), dtype=np.uint8)
            
            # Compute pixel-level metrics
            pixel_metrics = self._compute_pixel_level_metrics(pred_mask, gt_mask)
            stats.update(pixel_metrics)
            
            # Keep legacy IoU for backward compatibility
            stats['iou'] = pixel_metrics['iou_foreground']  # Use foreground IoU as legacy IoU
                
        elif dataset_type == 'synartifact':
            has_gt_artifacts = json_data.get('Artifacts annotation', [])

            if has_gt_artifacts:
                ground_bbox_list = []
                for annotation in has_gt_artifacts:
                    if 'rect_start' in annotation and 'rect_end' in annotation:
                        bbox = annotation['rect_start'] + annotation['rect_end']
                        ground_bbox_list.append(bbox)
                
                gt_mask = self._convert_to_binary_mask(ground_bbox_list, 'bbox_list', img_w, img_h)
            
                # Convert predictions to binary mask
                if pred_heatmap is not None:
                    pred_mask = self._convert_to_binary_mask(pred_heatmap, 'heatmap', img_w, img_h)
                elif result_bbox_list:
                    pred_mask = self._convert_to_binary_mask(result_bbox_list, 'bbox_list', img_w, img_h)
                else:
                    pred_mask = np.zeros((img_h, img_w), dtype=np.uint8)
            
                # Compute pixel-level metrics
                pixel_metrics = self._compute_pixel_level_metrics(pred_mask, gt_mask)
                stats.update(pixel_metrics)

                # Keep legacy IoU for backward compatibility
                stats['iou'] = pixel_metrics['iou_foreground']
            else:
                # Skip negative samples (samples without artifacts) for localization evaluation
                # Mark these metrics as None so they can be filtered out during aggregation
                stats.update({
                    'iou': None,
                    'miou': None,
                    'iou_foreground': None,
                    'iou_background': None,
                    'pixel_f1': None,
                    'pixel_precision': None,
                    'pixel_recall': None,
                    'tp_pixels': None,
                    'tn_pixels': None,
                    'fp_pixels': None,
                    'fn_pixels': None
                })
            
        elif dataset_type == 'loki':
            regional_problems = json_data['problems']['regional']
            ground_bbox_list = []
            
            for problem in regional_problems:
                if 'region' in problem:
                    x, y, w, h = problem['region']
                    bbox = [x, y, x + w, y + h]
                    ground_bbox_list.append(bbox)

            # Convert ground truth to binary mask
            gt_mask = self._convert_to_binary_mask(ground_bbox_list, 'bbox_list', img_w, img_h)
            
            if pred_heatmap is not None:
                    pred_mask = self._convert_to_binary_mask(pred_heatmap, 'heatmap', img_w, img_h)
            elif result_bbox_list:
                pred_mask = self._convert_to_binary_mask(result_bbox_list, 'bbox_list', img_w, img_h)
            else:
                pred_mask = np.zeros((img_h, img_w), dtype=np.uint8)
            
            # Compute pixel-level metrics
            pixel_metrics = self._compute_pixel_level_metrics(pred_mask, gt_mask)
            
            stats.update(pixel_metrics)
            
            # Keep legacy IoU for backward compatibility
            stats['iou'] = pixel_metrics['iou_foreground']
                
        elif dataset_type == 'richhf':
            artifact_map_path = "/home/jovyan/image-artifacts/data/richhf-18k/" + json_data['artifact_map_path']
            artifact_map = np.load(artifact_map_path)
            gt_mask = self._convert_to_binary_mask(artifact_map, 'heatmap', img_w, img_h)
            if gt_mask is not None:
                binarized_gt = self._binarize_heatmap(gt_mask)
                if binarized_gt is not None:
                    gt_mask = binarized_gt
                else:
                    gt_mask = np.zeros((img_h, img_w), dtype=np.uint8)

            if pred_heatmap is not None:
                pred_mask = self._convert_to_binary_mask(pred_heatmap, 'heatmap', img_w, img_h)
            elif result_bbox_list:
                pred_mask = self._convert_to_binary_mask(result_bbox_list, 'bbox_list', img_w, img_h)
            else:
                pred_mask = np.zeros((img_h, img_w), dtype=np.uint8)
            
            # Compute pixel-level metrics
            pixel_metrics = self._compute_pixel_level_metrics(pred_mask, gt_mask)
            stats.update(pixel_metrics)
            
            # Keep legacy IoU for backward compatibility
            stats['iou'] = pixel_metrics['iou_foreground']
        
        return stats
    
    def _handle_explanation_evaluation(self, dataset_type: str, json_data: Dict, result: Dict, 
                                       stats: Dict) -> Dict[str, Any]:
        """Handle explanation evaluation - compute ROUGE-L/CSS only for datasets with full captions."""
        
        # Only compute text scores for datasets with full image captions
        if dataset_type in ['synthscars', 'loki']:
            try:
                print(result)
                pred_caption = result.get('explanation', "").strip()
                ref_caption = ""

                if dataset_type == 'synthscars':
                    ref_caption = (json_data.get('caption') or '').strip()
                    # ref_caption = (json_data.get('caption') or '').strip().split('\n')[0]   # only use before To elaborate...
                elif dataset_type == 'loki':
                    ref_caption = (json_data['problems']['global'][0].get('desc', "")).strip()

                if ref_caption and pred_caption:
                    rouge_l, css = self.compute_global_caption_scores(ref_caption, pred_caption)
                    stats['rouge_l'] = rouge_l
                    stats['css'] = css
            except Exception:
                pass
                
        return stats

    @staticmethod
    def compute_f1_metrics(results: Dict[int, Dict]) -> Dict:
        """
        Compute F1, precision, recall from detailed evaluation results.
        
        Args:
            results: List of detailed evaluation results
            
        Returns:
            Dictionary with F1 metrics and TP/FP/FN/TN counts
        """
        tp = sum(1 for _, r in results.items() if r.get('classification') == 'TP')
        fp = sum(1 for _, r in results.items() if r.get('classification') == 'FP')
        fn = sum(1 for _, r in results.items() if r.get('classification') == 'FN')
        tn = sum(1 for _, r in results.items() if r.get('classification') == 'TN')
        
        # Compute precision, recall, F1
        precision = tp / (tp + fp) if (tp + fp) > 0 else 0.0
        recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
        f1_positive = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0.0
        
        precision_negative = tn / (tn + fn) if (tn + fn) > 0 else 0.0
        recall_negative = tn / (tn + fp) if (tn + fp) > 0 else 0.0
        f1_negative = 2 * (precision_negative * recall_negative) / (precision_negative + recall_negative) if (precision_negative + recall_negative) > 0 else 0.0
        
        # Macro F1 is the average of F1 scores for both classes
        macro_f1 = (f1_positive + f1_negative) / 2.0

        # Compute accuracy
        accuracy = (tp + tn) / len(results) if len(results) > 0 else 0.0

        return {
            'tp': tp,
            'fp': fp,
            'fn': fn,
            'tn': tn,
            'precision': precision,
            'recall': recall,
            'macro_f1': macro_f1,
            'f1_positive': f1_positive,
            'f1_negative': f1_negative,
            'precision_negative': precision_negative,
            'recall_negative': recall_negative,
            'accuracy': accuracy
        }